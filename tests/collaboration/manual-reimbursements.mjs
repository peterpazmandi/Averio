import assert from 'node:assert/strict';
import path from 'node:path';

export async function verifyManualReimbursements({ fixture: f, password, session, api, ok, artifacts }) {
    const page = await session(f.email, password);
    await page.clock.setFixedTime(new Date(f.date + 'T12:00:00Z'));
    const base = '/households/' + f.householdId;
    await page.goto('http://localhost:5173/app/transactions');
    await page.getByRole('button', { name: /Add transaction/ }).first().click();
    const editor = page.getByRole('dialog', { name: 'Add transaction', exact: true });
    await editor.getByLabel('Account', { exact: true }).selectOption(f.sharedAccountId);
    await editor.getByLabel('Description', { exact: true }).fill('Manual pharmacy');
    await editor.getByLabel(/^Amount/).first().fill('100');
    await editor.getByLabel('Track reimbursement for this payment', { exact: true }).check();
    await editor.getByRole('textbox', { name: 'Reimbursement provider', exact: true }).fill('Manual health fund');
    const estimate = editor.getByLabel(/^Reimbursement estimate/);
    await estimate.fill('100.0001');
    await editor.getByRole('alert').filter({ hasText: /cannot exceed the recorded expense/ }).waitFor();
    assert.equal(await estimate.evaluate(input => input.checkValidity()), false);
    await editor.getByRole('button', { name: 'Save transaction', exact: true }).click();
    assert.equal((await ok(page, base + '/reimbursements')).length, 0, 'Invalid estimate submitted a claim');
    await estimate.fill('100');
    assert.equal(await estimate.evaluate(input => input.checkValidity()), true, 'An estimate equal to the expense must be valid');
    await estimate.fill('25');
    assert.equal(await editor.getByRole('heading', { name: 'Reimbursement settings', exact: true }).evaluate(el => getComputedStyle(el).fontWeight), '600');
    await editor.getByRole('button', { name: 'Reimbursement cap (optional)', exact: true }).click();
    await editor.getByRole('button', { name: 'About Reimbursement cap (optional)', exact: true }).click();
    await page.getByRole('dialog', { name: 'Reimbursement cap (optional)', exact: true }).getByText(/upper limit for each claim/).waitFor();
    await page.keyboard.press('Escape');
    await editor.getByRole('textbox', { name: /^Reimbursement cap/ }).fill('20');
    await editor.getByRole('button', { name: 'Save transaction', exact: true }).click();
    await editor.waitFor({ state: 'hidden' });
    let claims = await ok(page, base + '/reimbursements');
    assert.equal(claims.length, 1);
    assert.equal(claims[0].potentialAmount, '20'); assert.equal(claims[0].expectedAmount, '0');
    assert.equal(claims[0].status, 'NeedsSubmission');
    assert.equal((await ok(page, base + '/recurring')).length, 0, 'Manual claim created a schedule');

    const categories = await ok(page, base + '/categories?kind=Expense');
    const ordinary = await ok(page, base + '/transactions', { method: 'POST', body: { accountId: f.sharedAccountId, kind: 'Expense', visibility: 'Household', merchant: 'Manual dental',
        note: null, occurredOn: f.date, items: [{ description: 'Dental visit', categoryId: categories.find(c => !c.isArchived).id, amount: '80' }], labelIds: [] } });
    const existing = await ok(page, base + '/transactions/' + ordinary.id);
    const before = await ok(page, base + '/accounts');
    await page.goto('http://localhost:5173/app/transactions?transaction=' + existing.id);
    const detail = page.getByRole('dialog');
    const track = detail.getByRole('button', { name: 'Track reimbursement', exact: true });
    await track.waitFor();
    const form = detail.locator('#transaction-editor');
    assert.ok((await track.boundingBox()).y < (await form.boundingBox()).y, 'Tracking action must be above the transaction form');
    await page.screenshot({ path: path.join(artifacts, 'reimbursement-action-top.png'), fullPage: true });
    await track.click();
    const create = page.getByRole('dialog', { name: 'Track reimbursement', exact: true });
    await create.getByRole('textbox', { name: 'Reimbursement provider', exact: true }).fill('Manual insurer');
    await create.getByLabel(/^Reimbursement estimate/).fill('10');
    const sent = page.waitForRequest(r => r.method() === 'POST' && r.url().endsWith('/reimbursements'));
    await create.getByRole('button', { name: 'Create claim', exact: true }).click();
    const payload = (await sent).postDataJSON();
    await create.waitFor({ state: 'hidden' });
    await detail.getByText('Manual insurer', { exact: false }).first().waitFor();
    const previousVersion = (await ok(page, base + '/reimbursements?transactionId=' + existing.id))[0].version;
    await detail.getByRole('button', { name: 'Edit reimbursement', exact: true }).click();
    const editClaim = page.getByRole('dialog', { name: 'Edit reimbursement', exact: true });
    for (const [subject, explanation] of [['Reimbursement provider', /organisation or person paying you back/], ['Expected payment', /confirm external submission/]]) {
        await editClaim.getByRole('button', { name: 'About ' + subject, exact: true }).click();
        await page.getByRole('dialog', { name: subject, exact: true }).getByText(explanation).waitFor();
        await page.keyboard.press('Escape');
        assert.equal(await editClaim.isVisible(), true, 'Help must preserve the reimbursement dialog');
    }
    await editClaim.getByRole('textbox', { name: 'Reimbursement provider', exact: true }).fill('Corrected insurer');
    const editEstimate = editClaim.getByLabel(/^Reimbursement estimate/);
    await editEstimate.fill('80.0001');
    assert.equal(await editEstimate.evaluate(input => input.checkValidity()), false);
    await editEstimate.fill('15');
    assert.equal(await editEstimate.evaluate(input => input.checkValidity()), true);
    await editClaim.getByLabel('Estimated days after submission', { exact: true }).fill('5');
    const days = editClaim.getByLabel('Days after recording the expense', { exact: true });
    const paymentDelay = editClaim.getByLabel('Estimated days after submission', { exact: true });
    const a = await days.boundingBox(), b = await paymentDelay.boundingBox();
    assert.ok(Math.abs(a.y - b.y) <= 2, 'Follow-up inputs should align on desktop');
    await page.screenshot({ path: path.join(artifacts, 'reimbursement-edit-follow-up.png'), fullPage: true });
    await editClaim.getByRole('button', { name: 'Save', exact: true }).click();
    await editClaim.waitFor({ state: 'hidden' });
    await detail.getByText('Corrected insurer', { exact: false }).first().waitFor();
    await detail.getByText('Claim history', { exact: true }).click();
    await detail.getByText('Reimbursement updated', { exact: false }).waitFor();
    const edited = (await ok(page, base + '/reimbursements?transactionId=' + existing.id))[0];
    assert.equal(edited.potentialAmount, '15'); assert.equal(edited.paymentDelayDays, 5);
    assert.equal(edited.events.filter(e => e.changeKind === 'Updated').length, 1);
    const staleEdit = await api(page, base + '/reimbursements/' + edited.id, { method: 'PUT', body: { expectedVersion: previousVersion, configuration: payload.configuration } });
    assert.equal(staleEdit.status, 409);

    const retries = await Promise.all([ok(page, base + '/reimbursements', { method: 'POST', body: payload }), ok(page, base + '/reimbursements', { method: 'POST', body: payload })]);
    assert.equal(retries[0].id, retries[1].id);
    const perPayment = await ok(page, base + '/reimbursements?transactionId=' + existing.id);
    assert.equal(perPayment.length, 1); assert.equal(perPayment[0].potentialAmount, '15');
    assert.deepEqual(await ok(page, base + '/accounts'), before, 'Tracking an existing expense changed balances');
    assert.equal((await api(page, base + '/reimbursements', { method: 'POST', body: { ...payload, expectedUpdatedAt: '2000-01-01T00:00:00Z' } })).status, 409);
    await detail.getByRole('button', { name: 'Cancel', exact: true }).click();
    await page.goto('http://localhost:5173/app/transactions');
    assert.equal((await ok(page, base + '/transactions/' + existing.id)).reimbursementStatus, 'NeedsSubmission');
    const bubble = page.locator('[data-transaction-id="' + existing.id + '"]');
    await bubble.getByText('Reimbursement · Needs submission', { exact: true }).waitFor();
    await page.setViewportSize({ width: 375, height: 1000 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: path.join(artifacts, 'manual-reimbursement-mobile.png'), fullPage: true });
    console.log('PASS manual claims from new/recorded ordinary expenses, shared form, duplicate retries, unchanged balances and no recurring schedule');
}
