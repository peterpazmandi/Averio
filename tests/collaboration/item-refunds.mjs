import assert from 'node:assert/strict';
import path from 'node:path';

export async function verifyItemRefunds({ fixture: f, password, session, api, ok, poll, localeFile, artifacts, control }) {
    const page = await session(f.email, password);
    await page.clock.setFixedTime(new Date(f.date + 'T12:00:00Z'));
    const base = '/households/' + f.householdId;
    const account = await ok(page, base + '/accounts', { method: 'POST', body: {
        name: 'Returns account', type: 'Cash', scope: 'Household', ownerHouseholdMemberIds: [], visibility: 'Household',
        includeInHouseholdReports: true, currency: 'EUR', balanceAnchorAmount: '0', balanceAnchorDate: f.date,
    } });
    const categories = await ok(page, base + '/categories?kind=Expense');
    const incomeCategory = (await ok(page, base + '/categories?kind=Income'))[0];
    const categoryA = categories[0], categoryB = categories[1];
    const stats = () => ok(page, base + `/statistics/category-cash-flow?from=${f.date}&to=${f.date}&period=Day`);
    const categoryAmount = (s, id) => s.periods.filter(x => x.categoryId === id).reduce((sum, x) => sum + Number(x.expenseAmount), 0);
    const incomeTotal = s => s.periods.reduce((sum, x) => sum + Number(x.incomeAmount), 0);
    const beforeStats = await stats();
    const post = (kind, items) => ok(page, base + '/transactions', { method: 'POST', body: {
        accountId: account.id, kind, visibility: 'Household', merchant: 'Refund browser shop', note: null, occurredOn: f.date, items, labelIds: [],
    } });
    const original = await post('Expense', [{ description: 'Returned shoes', categoryId: categoryA.id, amount: '120' }, { description: 'Returned shirt', categoryId: categoryB.id, amount: '80' }]);
    const source = () => ok(page, base + '/transactions/' + original.id);
    const balance = async () => (await ok(page, base + '/accounts')).find(a => a.id === account.id).currentBalanceAmount;
    const refundList = () => ok(page, base + '/transactions/' + original.id + '/refunds');
    let saved = await source();
    const a = saved.items[0].id, b = saved.items[1].id;
    await page.goto('http://localhost:5173/app/transactions?transaction=' + original.id);
    const region = () => page.getByRole('region', { name: 'Item refunds', exact: true });
    const merchant = page.getByRole('dialog', { name: 'Edit transaction', exact: true }).getByLabel('Merchant / Store', { exact: true });
    const editor = page.getByRole('dialog', { name: 'Edit transaction', exact: true });
    const saveButton = () => editor.getByRole('button', { name: 'Save transaction', exact: true });
    const markEditor = () => editor.evaluate(el => { el.dataset.refundSession = 'kept-open'; });
    const assertEditorKeptOpen = async () => assert.equal(await editor.getAttribute('data-refund-session'), 'kept-open', 'Refund changes must keep the same dialog mounted');
    await region().getByRole('button', { name: 'Add refund', exact: true }).click();
    const cachedPicker = page.getByRole('dialog', { name: 'Add refund', exact: true });
    await cachedPicker.getByLabel('Link an existing incoming transaction', { exact: true }).check();
    await cachedPicker.getByText('No matching incoming transactions.', { exact: true }).waitFor();
    await cachedPicker.getByRole('button', { name: 'Cancel', exact: true }).click();
    await editor.getByRole('button', { name: 'Close', exact: true }).first().click();
    await page.getByRole('button', { name: /Add transaction/ }).first().click();
    const createEditor = page.getByRole('dialog', { name: 'Add transaction', exact: true });
    await createEditor.getByLabel('Income', { exact: true }).check();
    await createEditor.getByLabel('Account', { exact: true }).selectOption(account.id);
    await createEditor.getByLabel('Description', { exact: true }).fill('Fresh refund candidate');
    await createEditor.getByLabel(/^Amount/).first().fill('5');
    const createdResponse = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/transactions'));
    await createEditor.getByRole('button', { name: 'Save transaction', exact: true }).click();
    const created = await (await createdResponse).json();
    await createEditor.waitFor({ state: 'hidden' });
    await page.locator('[data-transaction-id="' + original.id + '"] button').click();
    await region().getByRole('button', { name: 'Add refund', exact: true }).click();
    await cachedPicker.getByLabel('Link an existing incoming transaction', { exact: true }).check();
    await cachedPicker.locator('[data-credit-id="' + created.id + '"]').waitFor();
    await cachedPicker.getByRole('button', { name: 'Cancel', exact: true }).click();
    const createdRecord = await ok(page, base + '/transactions/' + created.id);
    await ok(page, base + '/transactions/' + created.id + '?expectedUpdatedAt=' + encodeURIComponent(createdRecord.updatedAt), { method: 'DELETE' });
    await editor.getByRole('radio', { name: 'Income', exact: true }).check();
    assert.equal(await region().getByRole('button', { name: 'Add refund', exact: true }).isDisabled(), true, 'An unsaved transaction type change also blocks refunds');
    await editor.getByRole('radio', { name: 'Expense', exact: true }).check();
    await merchant.fill('Unsaved receipt edit');
    assert.equal(await region().getByRole('button', { name: 'Add refund', exact: true }).isDisabled(), true, 'Save the editing draft before changing its refund revision');
    await merchant.fill('Refund browser shop');
    await region().getByRole('button', { name: 'Add refund', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Add refund', exact: true });
    await dialog.getByRole('combobox', { name: 'Receipt item', exact: true }).selectOption(a);
    await dialog.getByLabel(/^Refund amount/).fill('20');
    assert.equal(await dialog.getByRole('button', { name: 'Record refund', exact: true }).isDisabled(), true, 'Actual receipt confirmation is required');
    await dialog.getByLabel('I confirm that this money was actually refunded.', { exact: true }).check();
    await markEditor();
    let failRefresh = true;
    const detailRoute = '**/api/v1/households/' + f.householdId + '/transactions/' + original.id;
    const unavailableDetail = route => route.request().method() === 'GET' && failRefresh
        ? route.fulfill({ status: 503, contentType: 'application/problem+json', body: JSON.stringify({ title: 'Temporary refresh failure', status: 503 }) })
        : route.continue();
    await page.route(detailRoute, unavailableDetail);
    let recordWrites = 0, reversalWrites = 0;
    page.on('request', request => {
        if (request.method() !== 'POST') return;
        if (request.url().endsWith('/transactions/' + original.id + '/refunds')) recordWrites++;
        if (request.url().includes('/transactions/' + original.id + '/refunds/') && request.url().endsWith('/cancellation')) reversalWrites++;
    });
    const sent = page.waitForRequest(r => r.method() === 'POST' && r.url().endsWith('/transactions/' + original.id + '/refunds'));
    await dialog.getByRole('button', { name: 'Record refund', exact: true }).click();
    const payload = (await sent).postDataJSON();
    await dialog.waitFor({ state: 'hidden' });
    const refreshFailed = 'Refund changes are saved, but transaction details could not be refreshed. Retry loading them to continue editing.';
    await editor.getByRole('alert').filter({ hasText: refreshFailed }).waitFor();
    await assertEditorKeptOpen();
    assert.equal((await refundList()).length, 1, 'Failed refresh must not repeat the money write');
    assert.equal(await saveButton().isDisabled(), true);
    assert.equal(await editor.locator('#transaction-editor').evaluate(form => form.inert), true);
    assert.equal(await region().getByRole('button', { name: 'Add refund', exact: true }).isDisabled(), true);
    failRefresh = false;
    const walletRoute = '**/api/v1/households/' + f.householdId + '/personal-money/me';
    const unavailableWallet = route => route.fulfill({ status: 503, contentType: 'application/problem+json', body: JSON.stringify({ title: 'Temporary wallet failure', status: 503 }) });
    await page.route(walletRoute, unavailableWallet);
    const walletRetry = page.waitForResponse(r => new URL(r.url()).pathname.endsWith('/personal-money/me') && r.status() === 503);
    await editor.getByRole('button', { name: 'Retry refresh', exact: true }).click();
    await walletRetry;
    await editor.getByRole('button', { name: 'Retry refresh', exact: true }).waitFor();
    assert.equal(await saveButton().isDisabled(), true, 'Wait for fresh Personal Money as well as the source revision');
    assert.equal((await refundList()).length, 1);
    await page.unroute(walletRoute, unavailableWallet);
    await editor.getByRole('button', { name: 'Retry refresh', exact: true }).click();
    await poll(() => saveButton().isEnabled(), 'retry unlocks the refreshed transaction');
    assert.equal(recordWrites, 1, 'Refresh retries only read saved state, never repost the refund');
    await assertEditorKeptOpen();
    await page.unroute(detailRoute, unavailableDetail);
    await poll(async () => (await region().getByTestId('refund-net-expense').textContent()).replace(/\s/g, '') === '€180.00', 'net receipt after first item refund');
    assert.equal(await editor.locator('#transaction-editor').evaluate(form => form.inert), false);
    saved = await source();
    await merchant.fill('Edited after refund');
    const updatedAfterRefund = page.waitForRequest(r => r.method() === 'PUT' && r.url().endsWith('/transactions/' + original.id));
    await saveButton().click();
    const editedRequest = (await updatedAfterRefund).postDataJSON();
    assert.equal(editedRequest.expectedUpdatedAt, saved.updatedAt, 'Ordinary edits must use the refreshed refund revision');
    assert.deepEqual(editedRequest.items.map(i => i.existingItemId), [a, b]);
    assert.deepEqual(editedRequest.items.map(i => i.amount), ['120', '80'], 'Saving metadata retains original paid amounts');
    await editor.waitFor({ state: 'hidden' });
    assert.equal((await source()).merchant, 'Edited after refund');
    assert.equal((await source()).amount, '180');
    await page.goto('http://localhost:5173/app/transactions?transaction=' + original.id);
    await region().waitFor();
    const initialRefund = (await refundList())[0];
    const retried = await ok(page, base + '/transactions/' + original.id + '/refunds', { method: 'POST', body: payload });
    assert.equal(retried.id, initialRefund.id); assert.equal((await refundList()).length, 1);
    assert.equal((await ok(page, base + '/transactions/' + initialRefund.creditTransactionId)).kind, 'Refund');
    assert.equal(await balance(), '-180');
    const incoming = await post('Income', [{ description: 'Recorded bank return', categoryId: incomeCategory.id, amount: '15' }]);
    // Put the target beyond the first page; searches must reach the saved history.
    const unrelated = [];
    await control('/advance', { seconds: 1 });
    for (let i = 0; i < 27; i++) unrelated.push(await post('Income', [{ description: 'Unrelated credit ' + i, categoryId: incomeCategory.id, amount: '1' }]));
    const beforeLink = await balance();
    await region().getByRole('button', { name: 'Add refund', exact: true }).click();
    await dialog.getByRole('combobox', { name: 'Receipt item', exact: true }).selectOption(b);
    await dialog.getByLabel('Link an existing incoming transaction', { exact: true }).check();
    const candidate = () => dialog.locator('[data-credit-id="' + incoming.id + '"] input[type=radio]');
    await dialog.getByRole('button', { name: 'Load more transactions', exact: true }).waitFor();
    assert.equal(await candidate().count(), 0, 'The older target is not on the first page');
    await dialog.getByRole('button', { name: 'Load more transactions', exact: true }).click();
    await candidate().check();
    await dialog.getByLabel('I confirm that this money was actually refunded.', { exact: true }).check();
    const filterToggle = dialog.getByRole('button', { name: 'Filters', exact: true });
    assert.equal(await filterToggle.getAttribute('aria-expanded'), 'false');
    assert.equal(await dialog.getByLabel('Search merchant, item or note', { exact: true }).isVisible(), false);
    await filterToggle.click();
    await dialog.getByLabel('Search merchant, item or note', { exact: true }).fill('No such bank credit');
    await dialog.getByText('No matching incoming transactions.', { exact: true }).waitFor();
    assert.equal(await dialog.getByRole('button', { name: 'Link refund', exact: true }).isDisabled(), true, 'Filter changes clear selection and consent');
    const filteredRequest = page.waitForRequest(r => r.method() === 'GET' && new URL(r.url()).searchParams.get('search') === 'Recorded bank return');
    await dialog.getByLabel('Search merchant, item or note', { exact: true }).fill('Recorded bank return');
    const filteredUrl = new URL((await filteredRequest).url());
    assert.equal(filteredUrl.searchParams.get('from'), f.date);
    assert.equal(filteredUrl.searchParams.get('to'), f.date);
    assert.equal(filteredUrl.searchParams.get('pageSize'), '25');
    await candidate().check();
    assert.equal(await dialog.locator('[name=refund-credit]').count(), 1, 'Server search finds the older target without fetching every page');
    await dialog.getByLabel('I confirm that this money was actually refunded.', { exact: true }).check();
    await filterToggle.click();
    assert.equal(await filterToggle.getAttribute('aria-expanded'), 'false');
    assert.equal(await candidate().isChecked(), true, 'Collapsing filters preserves the selected credit');
    assert.equal(await dialog.getByRole('button', { name: 'Link refund', exact: true }).isEnabled(), true, 'Collapsing filters preserves consent');
    await filterToggle.click();
    assert.equal(await dialog.getByLabel('Search merchant, item or note', { exact: true }).inputValue(), 'Recorded bank return');
    await page.screenshot({ path: path.join(artifacts, 'item-refund-search-selected.png'), fullPage: false });
    await dialog.getByLabel('Received from', { exact: true }).fill('9999-12-31');
    await dialog.getByRole('alert').filter({ hasText: /Choose dates/ }).waitFor();
    assert.equal(await dialog.getByRole('button', { name: 'Link refund', exact: true }).isDisabled(), true);
    await dialog.getByRole('button', { name: 'Reset filters', exact: true }).click();
    await dialog.getByLabel('Search merchant, item or note', { exact: true }).fill('Recorded bank return');
    await candidate().check();
    await dialog.getByLabel('I confirm that this money was actually refunded.', { exact: true }).check();
    await dialog.getByRole('button', { name: 'Link refund', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    await poll(async () => (await source()).amount === '165', 'linked return net expense');
    assert.equal(await balance(), beforeLink, 'Existing credit was counted twice');
    assert.equal((await ok(page, base + '/transactions/' + incoming.id)).kind, 'Refund');
    for (const extra of unrelated) {
        const record = await ok(page, base + '/transactions/' + extra.id);
        await ok(page, base + '/transactions/' + extra.id + '?expectedUpdatedAt=' + encodeURIComponent(record.updatedAt), { method: 'DELETE' });
    }
    const after = await stats();
    assert.equal(categoryAmount(after, categoryA.id) - categoryAmount(beforeStats, categoryA.id), 100);
    assert.equal(categoryAmount(after, categoryB.id) - categoryAmount(beforeStats, categoryB.id), 65);
    assert.equal(incomeTotal(after), incomeTotal(beforeStats), 'Refund inflated income');
    for (const [itemId, amount] of [[a, '100'], [b, '65']]) {
        await region().getByRole('button', { name: 'Add refund', exact: true }).click();
        await dialog.getByRole('combobox', { name: 'Receipt item', exact: true }).selectOption(itemId);
        await dialog.getByLabel(/^Refund amount/).fill(String(Number(amount) + 0.01));
        await dialog.getByRole('alert').filter({ hasText: /remaining cost/ }).waitFor();
        assert.equal(await dialog.getByRole('button', { name: 'Record refund', exact: true }).isDisabled(), true);
        await dialog.getByLabel(/^Refund amount/).fill(amount);
        await dialog.getByLabel('I confirm that this money was actually refunded.', { exact: true }).check();
        await dialog.getByRole('button', { name: 'Record refund', exact: true }).click();
        await dialog.waitFor({ state: 'hidden' });
        await poll(async () => (await source()).items.find(i => i.id === itemId).amount === '0', 'full item return');
    }
    saved = await source();
    assert.equal(saved.amount, '0'); assert.equal(await balance(), '0');
    assert.deepEqual(saved.items.map(i => i.refundedAmount), ['120', '80']);
    assert.equal(await region().getByRole('button', { name: 'Add refund', exact: true }).isDisabled(), true);
    const records = await refundList();
    assert.equal(records.length, 4); assert.equal(new Set(records.map(r => r.creditTransactionId)).size, 4);
    const linked = records.find(r => r.creditTransactionId === incoming.id);
    await merchant.fill('Unsaved before reversal');
    assert.equal(await region().locator('[data-refund-id="' + linked.id + '"]').getByRole('button', { name: 'Reverse refund', exact: true }).isDisabled(), true);
    await merchant.fill('Edited after refund');
    await markEditor();
    failRefresh = true;
    await page.route(detailRoute, unavailableDetail);
    await region().locator('[data-refund-id="' + linked.id + '"]').getByRole('button', { name: 'Reverse refund', exact: true }).click();
    const reversal = page.getByRole('dialog', { name: 'Reverse this refund?', exact: true });
    await reversal.getByRole('button', { name: 'Reverse refund', exact: true }).click();
    await reversal.waitFor({ state: 'hidden' });
    await editor.getByRole('alert').filter({ hasText: refreshFailed }).waitFor();
    await assertEditorKeptOpen();
    const cancelledVersion = (await refundList()).find(r => r.id === linked.id).version;
    failRefresh = false;
    await editor.getByRole('button', { name: 'Retry refresh', exact: true }).click();
    await poll(() => saveButton().isEnabled(), 'reversal retry unlocks ordinary edits');
    await assertEditorKeptOpen();
    await page.unroute(detailRoute, unavailableDetail);
    assert.equal((await refundList()).find(r => r.id === linked.id).version, cancelledVersion, 'Retrying refresh must not repeat a reversal');
    assert.equal(reversalWrites, 1, 'Refresh retries must not repost the cancellation');
    await poll(async () => (await source()).amount === '15', 'reversal restores original item cost');
    saved = await source();
    await merchant.fill('Edited after reversal');
    const updatedAfterReversal = page.waitForRequest(r => r.method() === 'PUT' && r.url().endsWith('/transactions/' + original.id));
    await saveButton().click();
    assert.equal((await updatedAfterReversal).postDataJSON().expectedUpdatedAt, saved.updatedAt);
    await editor.waitFor({ state: 'hidden' });
    assert.equal((await source()).merchant, 'Edited after reversal');
    assert.equal((await source()).amount, '15');
    await page.goto('http://localhost:5173/app/transactions?transaction=' + original.id);
    await region().waitFor();
    await merchant.fill('Keep my concurrent draft');
    saved = await source();
    await control('/advance', { seconds: 1 });
    await ok(page, base + '/transactions/' + original.id, { method: 'PUT', body: {
        accountId: saved.accountId, kind: saved.kind, visibility: saved.visibility, merchant: saved.merchant,
        note: 'Saved by another session', occurredOn: saved.occurredOn, labelIds: saved.labels.map(label => label.id),
        expectedUpdatedAt: saved.updatedAt, items: saved.items.map(item => ({ existingItemId: item.id,
            description: item.description, categoryId: item.categoryId, amount: String(Number(item.amount) + Number(item.refundedAmount ?? '0')) })),
    } });
    const conflictedSave = page.waitForResponse(r => r.request().method() === 'PUT' && r.url().endsWith('/transactions/' + original.id) && r.status() === 409);
    await saveButton().click();
    await conflictedSave;
    await editor.getByRole('alert').waitFor();
    assert.equal(await merchant.inputValue(), 'Keep my concurrent draft', 'External changes must not replace typed edits or silently advance their revision');
    assert.equal((await source()).merchant, 'Edited after reversal');
    await editor.getByRole('button', { name: 'Cancel', exact: true }).click();
    await page.goto('http://localhost:5173/app/transactions?transaction=' + original.id);
    await region().waitFor();
    assert.equal(await balance(), '0', 'Unlinking existing bank credit must preserve cash');
    const restoredIncome = await ok(page, base + '/transactions/' + incoming.id);
    assert.equal(restoredIncome.status, 'Posted');
    assert.equal(restoredIncome.kind, 'Income');
    assert.equal(restoredIncome.items[0].description, 'Recorded bank return');
    assert.equal(restoredIncome.items[0].categoryId, incomeCategory.id);
    await region().locator('[data-refund-id="' + initialRefund.id + '"]').getByRole('link', { name: 'View returned money', exact: true }).click();
    await page.getByRole('link', { name: 'View original expense', exact: true }).waitFor();
    assert.equal(await page.getByRole('dialog').getByText('Income', { exact: true }).count(), 0);
    await page.getByRole('link', { name: 'View original expense', exact: true }).click();
    await region().waitFor();
    const final = await stats();
    assert.equal(categoryAmount(final, categoryA.id) - categoryAmount(beforeStats, categoryA.id), 0);
    assert.equal(categoryAmount(final, categoryB.id) - categoryAmount(beforeStats, categoryB.id), 15);
    assert.equal(incomeTotal(final), incomeTotal(beforeStats) + 15);
    // The fixture clock is frozen: make the preview newer than the voided credits
    // so UUID tie ordering cannot push it beyond the first result page.
    await control('/advance', { seconds: 1 });
    const preview = await post('Income', [{ description: 'Bank return for the remaining receipt item', categoryId: incomeCategory.id, amount: '2' }]);

    for (const language of ['en', 'de', 'hu']) for (const theme of ['light', 'dark']) for (const width of [375, 1440]) {
        await page.evaluate(({ language, theme }) => { localStorage.setItem('i18nextLng', language); localStorage.setItem('averio.theme', theme); }, { language, theme });
        await page.setViewportSize({ width, height: 1000 });
        await page.goto('http://localhost:5173/app/transactions?transaction=' + original.id);
        const copy = localeFile('itemRefunds')['itemRefunds' + language.toUpperCase()];
        const claimCopy = localeFile('reimbursements')['reimbursements' + language.toUpperCase()];
        const panel = page.getByRole('region', { name: copy.title, exact: true });
        await panel.waitFor();
        await page.getByRole('heading', { name: claimCopy.title, exact: true }).waitFor();
        assert.notEqual(copy.title, claimCopy.title, 'Refunds and expense coverage claims need distinct names');
        assert.equal(await panel.evaluate(el => el.scrollWidth > el.clientWidth + 1), false, 'Localized refund heading overflow');
        await page.screenshot({ path: path.join(artifacts, `money-back-options-${language}-${theme}-${width}.png`), fullPage: false });
        await panel.getByRole('button', { name: copy.add, exact: true }).click();
        const adding = page.getByRole('dialog', { name: copy.add, exact: true });
        const checkHelp = async (subject, explanation) => {
            const help = adding.getByRole('dialog', { name: subject, exact: true, includeHidden: true });
            const helpId = await help.getAttribute('id');
            await adding.locator('button[popovertarget=' + JSON.stringify(helpId) + ']').click();
            await help.waitFor({ state: 'visible' });
            assert.ok((await help.textContent()).includes(explanation), 'The I component retains the explanation');
            await help.press('Escape');
            await help.waitFor({ state: 'hidden' });
            assert.equal(await adding.isVisible(), true, 'Closing help must not close the refund form');
        };
        assert.equal(await adding.getByText(copy.existingHelp, { exact: true }).isVisible(), false, 'Helper text starts inside its I component');
        await checkHelp(copy.mode, copy.existingHelp);
        await checkHelp(copy.stepReview, copy.noIncome);
        await adding.getByLabel(new RegExp('^' + copy.amount)).fill('1');
        await adding.getByLabel(copy.received, { exact: true }).check();
        assert.equal(await adding.getByRole('button', { name: copy.record, exact: true }).isEnabled(), true);
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, 'Item refund form overflow');
        await adding.locator('form').evaluate(form => { form.parentElement.scrollTop = 0; });
        await page.screenshot({ path: path.join(artifacts, `item-refund-${language}-${theme}-${width}.png`), fullPage: false });
        assert.equal(await adding.locator('form > [role=group]').count(), 3, 'The three numbered steps are separate accessible groups');
        await adding.getByLabel(copy.existingCredit, { exact: true }).check();
        await checkHelp(copy.filters, copy.matchHelp.split('{{amount}}')[0]);
        await adding.locator('[data-credit-id="' + preview.id + '"] input[type=radio]').check();
        assert.equal(await adding.getByLabel(copy.received, { exact: true }).isChecked(), false, 'Changing the recording mode resets consent');
        const localizedToggle = adding.locator('button[aria-controls$="-filters"]');
        assert.equal(await localizedToggle.getAttribute('aria-expanded'), 'false');
        assert.equal(await adding.getByLabel(copy.search, { exact: true }).isVisible(), false);
        await localizedToggle.click();
        await adding.getByLabel(copy.search, { exact: true }).fill('Bank return for the remaining receipt item');
        await adding.locator('[data-credit-id="' + preview.id + '"] input[type=radio]').check();
        await adding.getByLabel(copy.received, { exact: true }).check();
        assert.equal(await adding.getByRole('button', { name: copy.link, exact: true }).isEnabled(), true);
        await localizedToggle.click();
        assert.equal(await adding.getByLabel(copy.search, { exact: true }).isVisible(), false);
        assert.equal(await adding.locator('[name=refund-credit]:checked').count(), 1);
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, 'Filtered credit list overflow');
        await page.screenshot({ path: path.join(artifacts, `item-refund-filter-${language}-${theme}-${width}.png`), fullPage: false });
        await adding.getByRole('button', { name: { en: 'Cancel', de: 'Abbrechen', hu: 'Mégse' }[language], exact: true }).click();
    }
    console.log('PASS item refund UI: manual/link existing credit, confirmation, different receipt items, caps, zero expense, net categories/no income, balances, idempotence, automatic editor refresh/new save revisions, failed reload retries without repeating writes, draft protection, reversal, origin navigation and EN/DE/HU responsive themes');
}
